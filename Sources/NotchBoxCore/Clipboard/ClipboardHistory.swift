import Foundation

/// Something the user copied.
public enum ClipboardContent: Equatable, Sendable {
    case text(String)
    /// Image data as it was on the pasteboard, with its type (`public.png` or `public.tiff`).
    case image(Data, type: String)
}

public struct ClipboardItem: Identifiable, Equatable, Sendable {
    public let id: Int
    public let content: ClipboardContent
    public let copiedAt: Date
}

/// The last things the user copied, newest first. Kept in memory only: nothing is written to disk.
public struct ClipboardHistory: Equatable, Sendable {
    public static let capacity = 20

    public private(set) var items: [ClipboardItem] = []
    private var nextID = 0

    public init() {}

    /// Adds `content` at the top. Copying something already in the list moves it to the top instead of
    /// adding it twice; the oldest item falls off past `capacity`.
    public mutating func record(_ content: ClipboardContent, at date: Date) {
        let id: Int
        if let index = items.firstIndex(where: { $0.content == content }) {
            id = items.remove(at: index).id
        } else {
            id = nextID
            nextID += 1
        }
        items.insert(ClipboardItem(id: id, content: content, copiedAt: date), at: 0)
        if items.count > Self.capacity {
            items.removeLast(items.count - Self.capacity)
        }
    }

    public mutating func remove(id: Int) {
        items.removeAll { $0.id == id }
    }

    public mutating func clear() {
        items.removeAll()
    }
}

/// Decides what to take from the pasteboard, from its type identifiers.
public enum ClipboardReading {
    public enum Kind: Equatable, Sendable {
        case text
        case image(type: String)
    }

    /// Markers password managers and other apps add to say "do not keep this" (nspasteboard.org).
    public static let privateMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    public static let textType = "public.utf8-plain-text"
    public static let imageTypes = ["public.png", "public.tiff"]
    static let fileURLType = "public.file-url"

    /// Bigger images are not kept, to keep memory use small.
    public static let maxImageBytes = 25_000_000
    /// How many characters of a text item the list shows.
    public static let previewLength = 120

    /// Text wins over an image (apps often add a picture of copied text); copied files and private
    /// items are skipped.
    public static func kind(of types: [String]) -> Kind? {
        let types = Set(types)
        guard types.isDisjoint(with: privateMarkers), !types.contains(fileURLType) else { return nil }
        if types.contains(textType) { return .text }
        if let image = imageTypes.first(where: types.contains) { return .image(type: image) }
        return nil
    }

    public static func content(text: String) -> ClipboardContent? {
        text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ? nil : .text(text)
    }

    public static func content(image data: Data, type: String) -> ClipboardContent? {
        guard !data.isEmpty, data.count <= maxImageBytes else { return nil }
        return .image(data, type: type)
    }

    /// The text on one line: runs of whitespace become one space, trimmed, cut to `previewLength`.
    public static func preview(of text: String) -> String {
        let words = text.split(whereSeparator: { $0.isWhitespace || $0.isNewline })
        return String(words.joined(separator: " ").prefix(previewLength))
    }
}
